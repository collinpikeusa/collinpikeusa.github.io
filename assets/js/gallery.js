/* ============================================================
   WE4RR — photo galleries

   Two rotating carousels, both fed from assets/photos/photos.json:
     • assets/photos/activations/  -> activation carousel
     • assets/photos/qsl/          -> QSL card carousel
   Plus the operator's own QSL card, and a shared lightbox.

   photos.json is regenerated by tools/build-photo-manifest.py and by
   .github/workflows/photos.yml. Sections hide themselves when empty.
   ============================================================ */
(function () {
  'use strict';

  var MANIFEST  = 'assets/photos/photos.json';
  var ACT_DIR   = 'assets/photos/activations/';
  var QSL_DIR   = 'assets/photos/qsl/';
  var ROTATE_MS = 6000;

  var reduceMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  var isLocal = /^(localhost|127\.0\.0\.1|\[::1\])$/.test(location.hostname) ||
                location.protocol === 'file:';

  function $(id) { return document.getElementById(id); }

  function esc(s) {
    return String(s == null ? '' : s)
      .replace(/&/g, '&amp;').replace(/</g, '&lt;')
      .replace(/>/g, '&gt;').replace(/"/g, '&quot;');
  }

  var MONTHS = ['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec'];
  function fmtDate(iso) {
    if (!iso) return '';
    var p = String(iso).slice(0, 10).split('-');
    if (p.length !== 3) return esc(iso);
    return (MONTHS[parseInt(p[1], 10) - 1] || p[1]) + ' ' + parseInt(p[2], 10) + ', ' + p[0];
  }

  /* ================= Reusable carousel =================
     opts = { src(item), caption(item) -> {title, meta[], note}, onSlideClick(i) } */

  function Carousel(root, items, opts) {
    var stage   = root.querySelector('.carousel__stage');
    var dotsEl  = root.querySelector('.carousel__dots');
    var countEl = root.querySelector('.carousel__count');
    var playBtn = root.querySelector('.carousel__play');
    var index = 0, timer = null, paused = reduceMotion;
    var clickable = typeof opts.onSlideClick === 'function';

    stage.innerHTML = items.map(function (it, i) {
      var src = opts.src(it);
      var cap = opts.caption(it) || {};
      var meta = (cap.meta || []).filter(Boolean).join('');
      // src is deferred to data-src: a slide is visibility:hidden until active,
      // and browsers never load loading="lazy" images inside a hidden element,
      // which left every slide blank on its first showing.
      return '' +
        '<figure class="slide' + (i === 0 ? ' is-active' : '') + '" role="group" ' +
              'aria-roledescription="slide" aria-label="' + (i + 1) + ' of ' + items.length + '">' +
          '<img class="slide__bg" data-src="' + src + '" alt="" aria-hidden="true" decoding="async">' +
          '<img class="slide__img" data-src="' + src + '" alt="' + esc(cap.alt || cap.title || '') + '"' +
               (clickable ? ' style="cursor:zoom-in"' : '') + ' decoding="async">' +
          '<figcaption class="slide__cap">' +
            (cap.title ? '<p class="slide__title">' + esc(cap.title) + '</p>' : '') +
            (meta ? '<p class="slide__meta">' + meta + '</p>' : '') +
            (cap.note ? '<p class="slide__note">' + esc(cap.note) + '</p>' : '') +
          '</figcaption>' +
        '</figure>';
    }).join('');

    var slides = Array.prototype.slice.call(stage.querySelectorAll('.slide'));

    if (items.length > 1) {
      dotsEl.innerHTML = items.map(function (it, i) {
        return '<button class="dot' + (i === 0 ? ' is-active' : '') + '" type="button" ' +
               'aria-label="Show item ' + (i + 1) + '"></button>';
      }).join('');
    }
    var dots = Array.prototype.slice.call(dotsEl.querySelectorAll('.dot'));

    function updateCount() {
      if (countEl) countEl.textContent = (index + 1) + ' / ' + items.length;
    }

    /* Load a slide plus its neighbours so advancing never shows a blank frame. */
    function loadSlide(i) {
      var slide = slides[(i + items.length) % items.length];
      if (!slide) return;
      slide.querySelectorAll('img[data-src]').forEach(function (img) {
        img.src = img.getAttribute('data-src');
        img.removeAttribute('data-src');
      });
    }
    function preloadAround(i) { loadSlide(i); loadSlide(i + 1); loadSlide(i - 1); }

    function go(n) {
      index = (n + items.length) % items.length;
      preloadAround(index);
      slides.forEach(function (s, i) { s.classList.toggle('is-active', i === index); });
      dots.forEach(function (d, i) { d.classList.toggle('is-active', i === index); });
      updateCount();
    }

    function start() {
      if (paused || items.length < 2) return;
      stop();
      timer = setInterval(function () { go(index + 1); }, ROTATE_MS);
    }
    function stop() { if (timer) { clearInterval(timer); timer = null; } }

    function setPaused(v) {
      paused = v;
      if (playBtn) {
        playBtn.setAttribute('data-paused', String(v));
        playBtn.setAttribute('aria-label', v ? 'Resume slideshow' : 'Pause slideshow');
      }
      if (v) stop(); else start();
    }

    root.querySelectorAll('.carousel__nav').forEach(function (btn) {
      btn.addEventListener('click', function () {
        go(index + (btn.getAttribute('data-dir') === 'next' ? 1 : -1));
        if (!paused) start();
      });
    });

    dots.forEach(function (d, i) {
      d.addEventListener('click', function () { go(i); if (!paused) start(); });
    });

    if (playBtn) playBtn.addEventListener('click', function () { setPaused(!paused); });

    if (clickable) {
      stage.addEventListener('click', function (e) {
        if (e.target.classList.contains('slide__img')) opts.onSlideClick(index);
      });
    }

    root.addEventListener('mouseenter', stop);
    root.addEventListener('mouseleave', function () { if (!paused) start(); });
    root.addEventListener('focusin', stop);
    root.addEventListener('focusout', function () { if (!paused) start(); });

    root.setAttribute('tabindex', '0');
    root.addEventListener('keydown', function (e) {
      if (e.key === 'ArrowLeft')  { go(index - 1); e.preventDefault(); }
      if (e.key === 'ArrowRight') { go(index + 1); e.preventDefault(); }
    });

    var x0 = null;
    stage.addEventListener('touchstart', function (e) { x0 = e.touches[0].clientX; stop(); }, { passive: true });
    stage.addEventListener('touchend', function (e) {
      if (x0 === null) return;
      var dx = e.changedTouches[0].clientX - x0;
      if (Math.abs(dx) > 45) go(index + (dx < 0 ? 1 : -1));
      x0 = null;
      if (!paused) start();
    }, { passive: true });

    document.addEventListener('visibilitychange', function () {
      if (document.hidden) stop(); else if (!paused) start();
    });

    preloadAround(0);
    updateCount();
    setPaused(reduceMotion);
    if (items.length < 2 && playBtn) playBtn.style.display = 'none';
  }

  /* ================= Lightbox ================= */

  var lb = {
    el: null, img: null, cap: null, items: [], i: 0, lastFocus: null, resolve: null,

    ensure: function () {
      if (this.el) return;
      var d = document.createElement('div');
      d.className = 'lightbox';
      d.setAttribute('role', 'dialog');
      d.setAttribute('aria-modal', 'true');
      d.setAttribute('aria-label', 'Image viewer');
      d.innerHTML =
        '<button class="lightbox__close" type="button" aria-label="Close">' +
          '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round"><path d="M18 6 6 18M6 6l12 12"/></svg></button>' +
        '<button class="lightbox__nav lightbox__nav--prev" type="button" aria-label="Previous">' +
          '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><path d="m15 18-6-6 6-6"/></svg></button>' +
        '<button class="lightbox__nav lightbox__nav--next" type="button" aria-label="Next">' +
          '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><path d="m9 18 6-6-6-6"/></svg></button>' +
        '<div><img class="lightbox__img" src="" alt=""><p class="lightbox__cap"></p></div>';
      document.body.appendChild(d);

      this.el  = d;
      this.img = d.querySelector('.lightbox__img');
      this.cap = d.querySelector('.lightbox__cap');

      var self = this;
      d.querySelector('.lightbox__close').addEventListener('click', function () { self.close(); });
      d.querySelector('.lightbox__nav--prev').addEventListener('click', function (e) { e.stopPropagation(); self.step(-1); });
      d.querySelector('.lightbox__nav--next').addEventListener('click', function (e) { e.stopPropagation(); self.step(1); });
      d.addEventListener('click', function (e) { if (e.target === d || e.target.tagName === 'DIV') self.close(); });
      document.addEventListener('keydown', function (e) {
        if (!self.el.classList.contains('is-open')) return;
        if (e.key === 'Escape')     self.close();
        if (e.key === 'ArrowLeft')  self.step(-1);
        if (e.key === 'ArrowRight') self.step(1);
      });
    },

    open: function (items, i, resolve) {
      this.ensure();
      this.items = items;
      this.resolve = resolve || function (it) { return it.src; };
      this.lastFocus = document.activeElement;
      this.show(i);
      this.el.classList.add('is-open');
      document.body.classList.add('no-scroll');
      this.el.querySelector('.lightbox__close').focus();
      var vis = items.length > 1 ? '' : 'none';
      this.el.querySelectorAll('.lightbox__nav').forEach(function (n) { n.style.display = vis; });
    },

    show: function (i) {
      this.i = (i + this.items.length) % this.items.length;
      var it = this.items[this.i];
      this.img.src = this.resolve(it);
      this.img.alt = it.alt || ('QSL card from ' + (it.callsign || it.file || ''));
      this.cap.textContent = (it.callsign || it.title || '') +
        (it.caption ? '  ·  ' + it.caption : '') +
        (this.items.length > 1 ? '   ·   ' + (this.i + 1) + ' / ' + this.items.length : '');
    },

    step: function (d) { this.show(this.i + d); },

    close: function () {
      this.el.classList.remove('is-open');
      document.body.classList.remove('no-scroll');
      this.img.src = '';
      if (this.lastFocus && this.lastFocus.focus) this.lastFocus.focus();
    }
  };

  /* ================= My own QSL card ================= */

  function setupOwnCard() {
    var fig = $('myCard');
    if (!fig) return;
    var img = fig.querySelector('img');
    var exts = ['jpg', 'jpeg', 'png', 'webp'];
    var base = 'assets/img/qsl-card-we4rr.';
    var n = 0;

    function tryNext() {
      if (n >= exts.length) { fig.remove(); return; }
      img.src = base + exts[n++];
    }

    img.addEventListener('error', tryNext);
    img.addEventListener('load', function () {
      fig.hidden = false;
      fig.addEventListener('click', function () {
        lb.open([{ src: img.src, alt: img.alt, callsign: 'WE4RR',
                   caption: 'Graphics by KJ4AXF' }], 0);
      });
    });

    tryNext();
  }

  /* ================= Wire-up ================= */

  function hintHtml(folder) {
    return '<div class="photo-hint">' +
      '<p style="margin:0 0 8px">No photos here yet.</p>' +
      '<p style="margin:0;font-size:.9rem">Drop images into <code>' + folder + '</code>, then run ' +
      '<code>python3 tools/build-photo-manifest.py</code>.</p>' +
      '<p style="margin:10px 0 0;font-size:.78rem;opacity:.75">Only visible during local preview — visitors see nothing.</p>' +
      '</div>';
  }

  function dropSection(section, hash) {
    if (section) section.remove();
    document.querySelectorAll('a[href="' + hash + '"]').forEach(function (a) { a.remove(); });
  }

  function setup(data) {
    setupOwnCard();

    var acts = (data && Array.isArray(data.activations)) ? data.activations : [];
    var qsls = (data && Array.isArray(data.qsl)) ? data.qsl : [];

    /* ---- activation carousel ---- */
    if (acts.length) {
      Carousel($('actCarousel'), acts, {
        src: function (it) { return ACT_DIR + encodeURIComponent(it.file); },
        caption: function (it) {
          var date = it.dateLabel || fmtDate(it.date);
          var meta = [];
          if (date) meta.push('<span>' + esc(date) + '</span>');
          if (it.ref) {
            meta.push('<a class="ref" href="https://pota.app/#/park/' + encodeURIComponent(it.ref) +
                      '" target="_blank" rel="noopener">' + esc(it.ref) + '</a>');
          }
          return { title: it.title || 'Activation', meta: meta, note: it.caption };
        }
      });
    } else if (isLocal) {
      $('actCarousel').innerHTML = hintHtml('assets/photos/activations/');
    } else {
      dropSection($('photos'), '#photos');
    }

    /* ---- QSL card carousel ---- */
    if (qsls.length) {
      Carousel($('qslCarousel'), qsls, {
        src: function (it) { return QSL_DIR + encodeURIComponent(it.file); },
        caption: function (it) {
          return {
            title: it.callsign || it.file,
            alt: 'QSL card from ' + (it.callsign || it.file),
            meta: [], note: it.caption
          };
        },
        onSlideClick: function (i) {
          lb.open(qsls, i, function (it) { return QSL_DIR + encodeURIComponent(it.file); });
        }
      });
    } else if (isLocal) {
      $('qslCarousel').innerHTML = hintHtml('assets/photos/qsl/');
    } else {
      dropSection($('qslcards'), '#qslcards');
    }
  }

  if (!window.fetch) { setup(null); return; }

  fetch(MANIFEST, { cache: 'no-cache' })
    .then(function (r) { if (!r.ok) throw new Error('HTTP ' + r.status); return r.json(); })
    .then(setup)
    .catch(function () { setup(null); });
})();
